function normalize(s: string) {return s.normalize('NFKC').toLocaleLowerCase('ja').replace(/[\s　]/g,'');}
export interface MachineEmojiPack {icons: readonly string[]; chant:string; recognized:boolean}
export function machineEmojiPack(machine: MachineDrawEntry): MachineEmojiPack {
  const title=normalize(machine.machine);
  const rule=ICON_RULES.find(item=>item.keys.some(key=>title.includes(normalize(key))));
  const icons: string[] = rule?[...rule.icons]:machine.kind==='pachislot'?['🎰','🔥','🎲','⚡️','✨','💥','🌈']:['🎡','✨','🎉','💥','🌈','⚡️','🎰'];
  if(/(?:light|ライト|甘デジ|99ver|87ver|79ver|49ver)/i.test(title))icons.push('🍬');
  else if(/(?:究極|超デカ|魔王|最終章|極限|クライマックス)/i.test(title))icons.push('💥');
  else if(/(?:premium|プレミアム)/i.test(title))icons.push('💎');
  const special=SPECIAL_CHANTS.find(item=>item.words.some(word=>title.includes(normalize(word))));
  const fact=machineTrivia(machine).highlight;
  const chant=special?.chant ?? `${icons[0]}${icons[1]} ${fact} ${icons[2]}${icons[3]}✨`;
  return {icons:[...new Set(icons)],chant,recognized:Boolean(rule)};
}
/** Stable, bounded emoji burst: no layout shift or continual animations. */
export function emojiBurst(pack: MachineEmojiPack, count=12): string[] {
  return Array.from({length:Math.min(14,Math.max(0,count))},(_,index)=>pack.icons[index%pack.icons.length]);
}
