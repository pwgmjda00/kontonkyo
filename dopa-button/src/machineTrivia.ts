function normalize(value:string){return value.normalize('NFKC').toLocaleLowerCase('ja');}
export function machineTrivia(machine:MachineDrawEntry): {theme:string; odds:string; context:string} {
  const name=normalize(machine.machine);
  const match=topics.find(t=>t.words.some(w=>name.includes(normalize(w))));
  const source=machine.sourceUrl.includes('sankyo-fever.jp')?'メーカー公式資料':'機種情報サイトなどの掲載資料';
  const odds=machine.kind==='pachislot'
    ? `この台の抽選対象は「${machine.category}」。スロットの「ボーナス合算」と「AT初当たり」は違う指標なので、同じ数字に見えても比較には注意。`
    : `この台の掲載条件は「${machine.category}」。通常時図柄揃い・チャージ込みの合算・RUSH突入などは、それぞれ別の確率です。`;
  const context=`掲載確率は${machine.publishedProbability}。出典は${source}です。${machine.approximate?' 数値は近似表記。':' データ上は分数として保持しています。'} このゲームの当選は模擬抽選で、実機の結果を予測しません。`;
  return {theme:match?.fact ?? `${machine.kind==='pachislot'?'パチスロ':'パチンコ'}の「${machine.machine}」。${machine.maker!=='未照合'&&machine.maker!=='未確認'?`登録メーカーは${machine.maker}。`:''}近いタイトルでもバージョン違いは別機種です。`,odds,context};
}
