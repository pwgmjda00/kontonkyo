function variantPoint(machine: MachineDrawEntry): string | null {
  const n=normalize(machine.machine);
  if(/(?:light|ライト|甘デジ|premium model|99ver|99\b|79ver|87ver|100ver|129ver|159ver|199ver|49\b)/i.test(n))
    return '同じシリーズの別バージョンと比べると、遊びのテンポや確率帯の違いが見えてくる。';
  if(/(?:\blt\b|lucky trigger|ラッキートリガー)/i.test(n))
    return '「LT」の文字はラッキートリガーの手がかり。初当たりの数字と上位状態への入口は別物。';
  if(/(?:2|3|4|5|6|Ⅱ|Ⅲ|Ⅳ|Ⅴ|Ⅵ|続編|最終章)/.test(n))
    return 'シリーズの続編らしさも見どころ。題材が同じでも機種ごとに違う顔を持つ。';
  return null;
}
function probabilityPoint(machine: MachineDrawEntry): string {
  const category=normalize(machine.category);
  if(machine.kind==='pachislot') {
    if(category.includes('合算')) return 'BIGとREGなど複数の抽選をまとめた「合算」。何が含まれる数字かで見え方が変わる。';
    if(category.includes('at')) return '「AT初当たり」はATへの入口の確率。ボーナスの出現率とは別の数字だ。';
    if(category.includes('ボーナス')) return 'ボーナスが登場する確率に注目。ATに入る確率とは同じ意味とは限らない。';
    return 'スロットは状態や設定で数字が変わることも。ひとつの確率にも別の物語が隠れている。';
  }
  if(category.includes('図柄揃い')) return '図柄が揃う瞬間を切り出した確率。チャージ込みの合算と比べると違いが際立つ。';
  if(category.includes('合算')) return 'いくつかの当たりをまとめた合算値。単純な図柄揃いとは分けて考えたい数字。';
  return '1回ごとの確率と、何回か続けたときの期待値は別物。「次こそ確定」は存在しない。';
}
export interface MachineTrivia { theme: string; highlight: string; odds: string; context: string }
export function machineTrivia(machine: MachineDrawEntry): MachineTrivia {
  const name=normalize(machine.machine);
  const story=stories.find(topic=>topic.words.some(word=>name.includes(normalize(word))));
  const theme=story?.intro ?? `「${machine.machine}」の世界観を一台に凝縮。名前から題材を想像するのも楽しみのひとつ。`;
  const highlight=story?.hook ?? variantPoint(machine) ?? '名前は一台でも、見せ方は十人十色。どんな世界観が待っているか注目。';
  const odds=`${machine.publishedProbability}という数字が今回の模擬抽選の入口。${probabilityPoint(machine)}`;
  const context=variantPoint(machine) ?? (machine.kind==='pachislot'
      ? 'パチスロなら「AT」「ボーナス」「合算」の違いに注目。種類が違う確率を比べると、見え方も変わる。'
      : 'パチンコは同じシリーズにもいろいろな確率帯がある。甘デジとミドルの違いを眺めるのも楽しい。');
  return {theme,highlight,odds,context};
}
