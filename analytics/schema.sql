CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY,project TEXT NOT NULL,day TEXT NOT NULL,name TEXT NOT NULL,mode TEXT NOT NULL,source TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS events_day ON events(day,project);
CREATE TABLE IF NOT EXISTS daily_counts(day TEXT NOT NULL,project TEXT NOT NULL,name TEXT NOT NULL,mode TEXT NOT NULL,source TEXT NOT NULL,n INTEGER NOT NULL,PRIMARY KEY(day,project,name,mode,source));

CREATE TABLE IF NOT EXISTS ingestion_quota(day TEXT PRIMARY KEY,n INTEGER NOT NULL CHECK(n>=0));
